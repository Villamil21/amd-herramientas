-- Tabla de Autorretenciones (dato maestro editable). ciiu_code es el código tal
-- como lo trae la fuente (111); normalized_code es la clave de comparación
-- (solo dígitos, a 4 posiciones si tiene 4 o menos: 0111). Tarifa en centésimas
-- de punto (1,10 % → 110): sin decimales binarios.
CREATE TABLE IF NOT EXISTS self_withholding_rates (
    id                 INTEGER PRIMARY KEY AUTOINCREMENT,
    ciiu_code          TEXT NOT NULL,
    normalized_code    TEXT NOT NULL UNIQUE,
    economic_activity  TEXT NOT NULL DEFAULT '',
    rate_bp            INTEGER NOT NULL CHECK (rate_bp >= 0 AND rate_bp <= 10000),
    source             TEXT NOT NULL DEFAULT '',
    created_at         TEXT NOT NULL,
    updated_at         TEXT NOT NULL
);

